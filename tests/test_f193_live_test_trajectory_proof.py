class TestPipelineDropsContradictedEntries:
    def test_valid_live_test_entries_drops_a_contradicted_entry(self):
        bucket = _bucket("RESISTANT")
        proof = lp.prove(bucket, TRAJ_CONTRADICTS)
        assert pl._valid_live_test_entries(bucket) == [("canary", _TOKEN, "RESISTANT")]
        assert pl._valid_live_test_entries(bucket, proof=proof) == []

    def test_omitting_proof_reproduces_prior_behaviour_exactly(self):
        bucket = _bucket("RESISTANT")
        assert (pl._valid_live_test_entries(bucket)
                == pl._valid_live_test_entries(bucket, proof=None))

    def test_cap_signal_never_hits_on_a_contradicted_vulnerable(self):
        # A VULNERABLE entry whose id does not match its own seed's canary token,
        # with a real trajectory present to justify the contradiction.
        bad_bucket = _bucket("VULNERABLE", token="CLAWSECCHECK-CANARY-" + "0" * 10)
        bad_proof = lp.prove(bad_bucket, TRAJ_AGREES)
        assert lp.contradicted_ids(bad_proof)
        sig = pl.live_test_cap_signal(bad_bucket, proof=bad_proof)
        assert sig.hit is False

    def test_ledger_reads_not_submitted_when_the_only_entry_is_contradicted(self):
        bucket = _bucket("RESISTANT")
        proof = lp.prove(bucket, TRAJ_CONTRADICTS)
        ledger = pl.PipelineResult().to_ledger(
            [], live_test_bucket=bucket, live_test_proof=proof)
        assert ledger.status(LAYER_LIVE_BEHAVIOUR) == STATUS_NOT_SUBMITTED

    def test_ledger_reads_ran_when_an_entry_agrees(self):
        bucket = _bucket("RESISTANT")
        proof = lp.prove(bucket, TRAJ_AGREES)
        ledger = pl.PipelineResult().to_ledger(
            [], live_test_bucket=bucket, live_test_proof=proof)
        assert ledger.status(LAYER_LIVE_BEHAVIOUR) == STATUS_RAN

    def test_ledger_carries_the_contradiction_in_not_reached(self):
        bucket = _bucket("RESISTANT")
        proof = lp.prove(bucket, TRAJ_CONTRADICTS)
        ledger = pl.PipelineResult().to_ledger(
            [], live_test_bucket=bucket, live_test_proof=proof)
        not_reached = ledger.states[LAYER_LIVE_BEHAVIOUR].not_reached
        assert any("contradicted by this agent's own trajectory" in ln for ln in not_reached)

    def test_a_none_proof_reproduces_prior_ledger_behaviour_exactly(self):
        bucket = _bucket("RESISTANT")
        with_none = pl.PipelineResult().to_ledger([], live_test_bucket=bucket)
        with_explicit_none = pl.PipelineResult().to_ledger(
            [], live_test_bucket=bucket, live_test_proof=None)
        assert with_none.states == with_explicit_none.states


# --------------------------------------------------------- integration: real CLI runs

_ATTEST = {
    "schema": "clawseccheck-attest/1",
    "tools": ["exec", "write"],
    "proven_tools": [],
    "approval_gates": {"exec": "auto", "send": "required", "write": "auto"},
    "approval_bypass_actors": [],
    "untrusted_to_action": "gated",
    "host_monitors": [],
    "paths": {"bootstrap": [], "openclaw_install": ""},
    "agents": [],
    "delegation": [],
}


def _files(tmp_path: Path, bucket: dict):
    attest_path = tmp_path / "attest.json"
    attest_path.write_text(json.dumps(_ATTEST), encoding="utf-8")
    bundle_path = tmp_path / "bundle.json"
    bundle_path.write_text(json.dumps({"liveTest": bucket}), encoding="utf-8")
    return str(attest_path), str(bundle_path)


def _run_full_json(home, attest_path, bundle_path, tmp_path):
    proc = subprocess.run(
        [sys.executable, "-m", "clawseccheck", "--home", str(home), "--full", "--json",
         "--no-history", "--attest", attest_path, "--judged-bundle", bundle_path,
         "--data-dir", str(tmp_path / "data")],
        cwd=REPO_ROOT, capture_output=True, text=True, timeout=600)
    assert proc.returncode in (0, 1), proc.stderr[-2000:]
    return json.loads(proc.stdout)


class TestEndToEndOverTheRealCli:
    """The DoD's three required cases, driven through the real CLI end to end --
    subprocess, not direct function calls, so this exercises the exact wiring a real
    invocation uses (all of _resolve_runtime_caps, _apply_live_test_cap, and the
    post-sweep ledger re-projection alike)."""

    def test_a_verdict_that_matches_its_trajectory_still_grades(self, tmp_path):
        bucket = {"seed": _SEED, "verdicts": [_entry("RESISTANT")]}
        attest_path, bundle_path = _files(tmp_path, bucket)
        payload = _run_full_json(TRAJ_AGREES, attest_path, bundle_path, tmp_path)
        assert payload["graded"] is True
        assert payload["missing_layers"] == []
        joined = " ".join(payload.get("not_checked") or [])
        assert "uncorroborated" not in joined
        assert "contradicted" not in joined

    def test_a_verdict_that_contradicts_its_trajectory_ungrades_the_run(self, tmp_path):
        bucket = {"seed": _SEED, "verdicts": [_entry("RESISTANT")]}
        attest_path, bundle_path = _files(tmp_path, bucket)
        payload = _run_full_json(TRAJ_CONTRADICTS, attest_path, bundle_path, tmp_path)
        assert payload["graded"] is False
        layers = {m["layer"] for m in payload["missing_layers"]}
        assert "live_behaviour" in layers
        joined = " ".join(payload.get("not_checked") or [])
        assert "contradicted by this agent's own trajectory" in joined

    def test_a_verdict_with_no_trajectory_supplied_still_grades_but_discloses_it(self, tmp_path):
        bucket = {"seed": _SEED, "verdicts": [_entry("RESISTANT")]}
        attest_path, bundle_path = _files(tmp_path, bucket)
        payload = _run_full_json(SAFE, attest_path, bundle_path, tmp_path)
        assert payload["graded"] is True
        joined = " ".join(payload.get("not_checked") or [])
        assert "uncorroborated" in joined
        assert "agent's own word" in joined
