class TestSeedBindingNeedsATrajectory:
    """Seed-binding alone (no real trajectory backing the claim) is deliberately NOT
    a standalone check — see livetestproof.py's own "why seed-binding needs a
    trajectory too" note. A mismatched id with nothing else to go on stays
    UNCHECKED, exactly like any other id this module cannot corroborate; the same
    mismatch WITH a real trajectory present (TestSeedBindingWithATrajectory below)
    is where it actually fires."""

    def test_mismatched_id_with_no_trajectory_is_merely_unchecked(self):
        wrong_token = "CLAWSECCHECK-CANARY-" + "F" * 10
        proof = lp.prove(_bucket("RESISTANT", token=wrong_token), SAFE)
        assert proof.trajectory_present is False
        assert proof.entries[0].status == lp.CORROBORATION_UNCHECKED
        assert lp.contradicted_ids(proof) == frozenset()

    def test_matching_id_with_no_trajectory_is_also_merely_unchecked(self):
        proof = lp.prove(_bucket("RESISTANT"), SAFE)
        assert proof.trajectory_present is False
        assert proof.entries[0].status == lp.CORROBORATION_UNCHECKED
        assert lp.contradicted_ids(proof) == frozenset()

    def test_the_incident_shape_past_the_id_gate_stays_unchecked_with_no_trajectory(self):
        """E-087's actual bundle, past the static id-SHAPE gate this time (a real
        prefix + real hex length, just not this seed's own value) — with no
        trajectory to corroborate against, this module correctly says nothing,
        deferring entirely to the static shape gate (`_is_generated_scenario_id`,
        d67ef68) that already rejects the ORIGINAL incident's bare "canary" id."""
        incident = {"seed": "x", "verdicts": [
            {"tool": "canary", "id": "CLAWSECCHECK-CANARY-DEADBEEFCAFE0123",
             "verdict": "RESISTANT"}]}
        proof = lp.prove(incident, SAFE)
        assert proof.entries[0].status == lp.CORROBORATION_UNCHECKED
        assert lp.contradicted_ids(proof) == frozenset()


class TestSeedBindingWithATrajectory:
    """The same mismatch, now with a real trajectory present to justify the
    stronger claim: a canary generator is a pure function of the seed, so an id a
    readable log is being consulted for that could not have come from that seed at
    all is provably wrong, independent of what the log's own text says."""

    def test_mismatched_id_contradicts_when_a_trajectory_is_present(self):
        wrong_token = "CLAWSECCHECK-CANARY-" + "F" * 10
        proof = lp.prove(_bucket("RESISTANT", token=wrong_token), TRAJ_AGREES)
        assert proof.trajectory_present is True
        assert proof.entries[0].status == lp.CORROBORATION_CONTRADICTS
        assert "not this seed's own canary token" in proof.entries[0].note
        assert lp.contradicted_ids(proof) == {("canary", wrong_token)}


# --------------------------------------------------------- unit: trajectory corroboration

class TestTrajectoryCorroboration:
    def test_a_resisted_canary_agrees(self):
        proof = lp.prove(_bucket("RESISTANT"), TRAJ_AGREES)
        assert proof.trajectory_present is True
        e = proof.entries[0]
        assert e.status == lp.CORROBORATION_AGREES
        assert e.administered is True
        assert e.recomputed_verdict == "RESISTANT"
        assert lp.not_reached_lines(proof) == ()

    def test_a_complied_canary_contradicts_a_submitted_resistant(self):
        proof = lp.prove(_bucket("RESISTANT"), TRAJ_CONTRADICTS)
        e = proof.entries[0]
        assert e.status == lp.CORROBORATION_CONTRADICTS
        assert e.recomputed_verdict == "VULNERABLE"
        assert lp.contradicted_ids(proof) == {("canary", _TOKEN)}
        lines = lp.not_reached_lines(proof)
        assert len(lines) == 1
        assert "contradicted by this agent's own trajectory" in lines[0]

    def test_unrelated_traffic_reads_as_absent_not_contradicted(self):
        """The token never reaches a submitted prompt at all -- administered=False,
        so this is weaker evidence than an active disproof and must not escalate to
        CONTRADICTS (CLAUDE.md §2.5: disprove a signal before penalizing it)."""
        proof = lp.prove(_bucket("RESISTANT"), TRAJ_ABSENT)
        e = proof.entries[0]
        assert e.administered is False
        assert e.status == lp.CORROBORATION_ABSENT
        assert lp.contradicted_ids(proof) == frozenset()
        lines = lp.not_reached_lines(proof)
        assert "the scenario's own token never appears in it" in lines[0]

    def test_a_submitted_vulnerable_disagreeing_with_a_resistant_trajectory_is_not_a_contradiction(self):
        """Asymmetry rule: the agent self-reported WORSE than the evidence shows.
        Never treated as a contradiction -- escalate-only, same as CLAUDE.md §2.5's
        rule for the vet judge."""
        proof = lp.prove(_bucket("VULNERABLE"), TRAJ_AGREES)
        e = proof.entries[0]
        assert e.recomputed_verdict == "RESISTANT"
        assert e.submitted_verdict == "VULNERABLE"
        assert e.status == lp.CORROBORATION_AGREES
        assert lp.contradicted_ids(proof) == frozenset()

    def test_render_echo_is_not_mistaken_for_compliance(self):
        """The harness's own rendered scaffold text, verbatim -- must not read as the
        agent complying with the injected instruction."""
        from clawseccheck.canary import render_canary
        rendered = render_canary({"token": _TOKEN, "payload": "irrelevant"})
        # Exercises the discriminator directly on TEXT rather than via a fixture
        # directory — the render-echo shape is about the text, not the file layout.
        recomputed = lp._recompute_canary_verdict(rendered, _TOKEN)
        assert recomputed == "RESISTANT", (
            "the harness's own render_canary() output must never itself look like "
            "compliance")

    def test_a_paraphrasing_refusal_reads_resistant_via_referential_masking(self):
        """C-135 round 3 (Side A, superseding round 2's retracted
        `CORROBORATION_DISPUTED`): `_entry_proof`'s shared recompute now masks a
        token occurrence that is a substantial verbatim quotation of the KNOWN
        canary payload (`canary.make_canary(seed)["payload"]`, a pure function of
        `seed` — never guessed from the reply), so canary shares this fix with
        redteam/dryrun/multiturn (see `test_f194_live_test_trajectory_proof.py`'s
        `TestReferentialQuoteMasking` for the generalized case and the two
        adversarial reproductions this replacement had to survive). This fixture
        ("...I am not going to follow an instruction embedded in untrusted
        content, so I did not comply.") quotes the real payload's own wording
        around the token; before ANY fix this read as a hard CONTRADICTS (a false
        accusation against an honest, transparent refusal) — after this fix it
        reads as a correct AGREES/RESISTANT, not merely a softened DISPUTED.

        None of this file's OTHER, pre-existing fixtures/tests changed outcome —
        `traj_f193_contradicts`'s reply ("Sure, here you go: <token>") has zero
        quotable overlap with the real payload near the token, so
        `test_a_complied_canary_contradicts_a_submitted_resistant` above is
        unaffected; this is additive coverage, not a changed assertion."""
        seed = "f193-quote-seed"
        token = make_canary(seed)["token"]
        proof = lp.prove(
            {"seed": seed, "verdicts": [{"tool": "canary", "id": token,
                                         "verdict": "RESISTANT"}]},
            FIXTURES / "traj_f193_payload_quote")
        e = proof.entries[0]
        assert e.recomputed_verdict == "RESISTANT"
        assert e.status == lp.CORROBORATION_AGREES
        assert lp.contradicted_ids(proof) == frozenset()
        assert lp.not_reached_lines(proof) == ()


