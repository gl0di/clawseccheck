"""F-193 (full scope): a canary live-test verdict is now cross-checked against real,
local evidence — not just the shape check `test_f193_live_test_id_validation.py`
already pins — before it may complete layer 5 of the ledger or set the grade cap.

Two independent legs, both in `clawseccheck/livetestproof.py`:

1. **Seed-binding.** `canary.make_canary(seed)` is deterministic, so a submitted id
   that does not match what THIS bundle's own seed would have generated is proven
   wrong without ever reading a trajectory.
2. **Trajectory corroboration.** When a local trajectory sidecar is readable, the
   submitted RESISTANT/VULNERABLE verdict is recomputed from the agent's own recorded
   reply (reusing `trajaudit`'s render-echo discriminator) and compared.

E-087's incident bundle (`{"seed": "x", "verdicts": [{"tool": "canary", "id":
"canary", "verdict": "RESISTANT"}]}`) is already rejected by the id-SHAPE gate
(`test_f193_live_test_id_validation.py`, commit d67ef68) before it ever reaches this
module. This file covers what that shape gate cannot: an id that IS shape-valid but
was never really generated by this seed, and a verdict a real trajectory disproves.

Deliberately scoped to canary only — see `livetestproof.py`'s own module docstring for
why redteam/dryrun/multiturn are follow-up scope, not silently dropped.

Offline, read-only, stdlib only. Uses the shipped fixtures only.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

from clawseccheck import livetestproof as lp
from clawseccheck import pipeline as pl
from clawseccheck.canary import make_canary
from clawseccheck.layers import LAYER_LIVE_BEHAVIOUR, STATUS_NOT_SUBMITTED, STATUS_RAN

REPO_ROOT = Path(__file__).resolve().parents[1]
FIXTURES = REPO_ROOT / "fixtures"
SAFE = str(FIXTURES / "home_safe")
TRAJ_AGREES = FIXTURES / "traj_f193_agrees"
TRAJ_CONTRADICTS = FIXTURES / "traj_f193_contradicts"
TRAJ_ABSENT = FIXTURES / "traj_f193_absent"

_SEED = "f193-seed"
_TOKEN = make_canary(_SEED)["token"]  # CLAWSECCHECK-CANARY-0A46B5EF9A


def _entry(verdict: str, *, token: str = _TOKEN) -> dict:
    return {"tool": "canary", "id": token, "verdict": verdict}


def _bucket(verdict: str, *, seed=_SEED, token: str = _TOKEN) -> dict:
    b = {"verdicts": [_entry(verdict, token=token)]}
    if seed is not None:
        b["seed"] = seed
    return b


