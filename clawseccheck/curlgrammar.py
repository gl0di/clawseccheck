# Every VALUE-taking option in the three categories above that this module
# does NOT mark HOP -- each is here because its value cannot redirect curl's
# own request to a different remote host/hop:
#   --noproxy: DISABLES proxying for matching hosts -- reduces hop surface,
#     never adds one.
#   --*-timeout/--*-time/--max-filesize/--limit-rate/--rate/--parallel-max/
#     --keepalive-time/--continue-at: numeric limits/offsets, not hosts.
#   --interface/--local-port: choose the LOCAL outbound interface/port, never
#     the remote destination.
#   --proto/--proto-default/--proto-redir: restrict/assume a URL SCHEME, not
#     a host; this module's own https:// requirement (decision 2) already
#     covers the scheme axis directly against the DEST word's literal text.
#   --request: the HTTP method string (GET/POST/...), not a host.
#   --proxy-cacert/--proxy-capath/--proxy-cert/--proxy-crlfile/--proxy-key/
#     --proxy-pinnedpubkey: TLS_MATERIAL role already (see OPTION_ROLE) --
#     also proxy-category, listed here too since this set is a plain
#     "not-HOP" membership check, not mutually exclusive with TLS_MATERIAL.
#   --proxy-cert-type/--proxy-key-type/--proxy-ciphers/--proxy-tls13-ciphers/
#     --proxy-service-name/--proxy-tlsauthtype/--proxy-tlspassword/
#     --proxy-tlsuser/--proxy-pass/--proxy-user/--socks5-gssapi-service/
#     --proxy-header: auth/algorithm/service-name STRINGS for a proxy or
#     SOCKS5 connection that is only ever reached through an actual
#     --proxy/--socks5/... flag -- which independently carries the HOP role
#     and refuses the exemption unconditionally. These values are inert
#     without a HOP flag also present on the line.
#   --haproxy-clientip: sets the client IP reported *to* the origin via the
