"""B-986: curl's own option grammar, as vetted data -- not
enumeration-by-reading-the-source.

Generated from a real, executed curl 8.5.0 (Ubuntu, `curl 8.5.0
(x86_64-pc-linux-gnu) libcurl/8.5.0 ...`, Release-Date 2023-12-06), captured
2026-09-25 by `curl --help all` plus a per-option EMPIRICAL arity probe (each
of curl's 258 documented long options fed an empty-string value and observed,
not just its --help text read) -- see this ticket's scratchpad
(`arity_oracle_v2.json`/`categories.json`/`help_all_8.5.0.txt`) for the raw
capture. `scripts/gen_curl_grammar.py` documents how to redo this capture
against a live curl and re-run the same transform that produced the tables
below.

Two curl-parser facts this whole module leans on (verified directly against
the same curl 8.5.0 binary, not assumed):
  * curl does NOT support `--option=value` glued long-option syntax --
    `curl --cert=/path` errors `option --cert=/path: is unknown` (the
    parser looks up the *entire* post-`--` text, `=` included, as one
    candidate option name; nothing named that exists). `curlargv.py`
    therefore never splits on `=`.
  * curl accepts an unambiguous PREFIX of a long option name in place of the
    full spelling (`--noprox` resolves to `--noproxy` because no other option
    starts with `noprox`). `curlargv.py` implements this via `OPTION_ARITY`/
    `OPTION_ROLE`'s own keys as the candidate set.

Every option gets exactly ONE role from the closed set below -- SAFE is an
explicit, deliberate member of that set (not a silent default with no
guard): `OPTION_ROLE` is total over every key of `OPTION_ARITY` (see
`test_curlgrammar.py`'s completeness test), and every value-taking option in
curl's own proxy/dns/connection `--help` categories that ISN'T HOP is
required (by the same test) to be a member of `_PROXY_DNS_CONN_SAFE_JUSTIFIED`
below, whose comment carries the justification.
"""
